"""Generate shared/follow_cases.json: motion-tracking maths computed by backend/app/follow.py.
frontend/src/tracking/follow.test.ts must reproduce them (the TS port in tracking/follow.ts).

Run:  .venv\\Scripts\\python.exe scripts\\make_follow_cases.py
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app import follow as FO  # noqa: E402
from app import motion as M  # noqa: E402


def r(v):
    if isinstance(v, float):
        return round(v, 9)
    if isinstance(v, list):
        return [r(x) for x in v]
    if isinstance(v, dict):
        return {k: r(x) for k, x in v.items()}
    return v


def wobble(n, x0, x1, y, w, h, spin=0.0, lost=(), jitter=0.004):
    out = []
    for i in range(n):
        u = i / max(1, n - 1)
        j = jitter * math.sin(i * 2.3) + jitter * 0.5 * math.cos(i * 5.1)
        c = 0.0 if i in lost else 0.9
        out.append([x0 + (x1 - x0) * u + j, y + 0.05 * math.sin(u * 3) + j, w * (1 + 0.3 * u), h * (1 + 0.3 * u), spin * u, c])
    return out


track_a = {"id": "ta", "mediaId": "land", "fps": 25, "k0": 10, "data": wobble(90, 0.2, 0.8, 0.45, 0.08, 0.16, spin=30, lost=range(40, 52))}
track_b = {"id": "tb", "mediaId": "port", "fps": 24, "k0": 0, "data": wobble(80, 0.3, 0.6, 0.3, 0.2, 0.12, spin=-200)}
metas = {"land": {"id": "land", "type": "video", "width": 1920, "height": 1080, "fps": 25, "duration": 6},
         "port": {"id": "port", "type": "video", "width": 1080, "height": 1920, "fps": 24, "duration": 5}}
TR0 = {"x": 0, "y": 0, "scale": 1, "rotation": 0, "opacity": 1, "flipH": False, "flipV": False, "crop": {"left": 0, "top": 0, "right": 0, "bottom": 0}}


def clip(cid, mid, start, inp, outp, **kw):
    c = {"id": cid, "mediaId": mid, "start": start, "inPoint": inp, "outPoint": outp, "speed": 1, "reverse": False, "freezeFrame": None,
         "fit": None, "transform": dict(TR0), "keyframes": {}, "filters": [], "text": None}
    for k, v in kw.items():
        if k == "transform":
            c["transform"] = {**TR0, **v}
        else:
            c[k] = v
    return c


main1 = clip("m1", "land", 0, 0.5, 3.0, fit="fill", reframe={"trackId": "ta", "third": "left", "smoothing": 0.6})
main2 = clip("m2", "port", 2.5, 0.2, 2.7, speed=1.25, keyframes={"scale": [{"time": 0, "value": 1, "easing": "linear"}, {"time": 2, "value": 1.2, "easing": "inout"}]})
ov = clip("o1", "port", 0.5, 0, 1.5, transform={"scale": 0.5, "x": 200, "y": 300, "rotation": 10})
txt = clip("t1", None, 0.3, 0, 2.0, transform={"x": 0, "y": -150}, text={"content": "hi"},
           follow={"trackId": "ta", "clipId": "m1", "scale": True, "rotation": True, "smoothing": 0.3, "safe": True})
txt2 = clip("t2", None, 2.6, 0, 1.6, transform={"x": 60, "y": 0, "scale": 0.8}, text={"content": "b"},
            follow={"trackId": "tb", "clipId": "gone", "position": True, "smoothing": 0.0})
stk = clip("s1", None, 0.6, 0, 1.2, follow={"trackId": "tb", "clipId": "o1", "rotation": True, "smoothing": 0.5})
blur = clip("b1", None, 0.0, 0, 2.5, adjustment=True, region={"effect": "blur", "padding": 0.3}, follow={"trackId": "ta", "smoothing": 0.15})
project = {"settings": {"width": 1080, "height": 1920, "fps": 30, "background": {"mode": "blur"}}, "motionTracks": [track_a, track_b],
           "tracks": [{"type": "video", "clips": [main1, main2]}, {"type": "overlay", "clips": [ov]}, {"type": "overlay", "clips": [blur, stk]},
                      {"type": "text", "clips": [txt, txt2]}]}
sizes = {"t1": [420.0, 160.0], "t2": [200.0, 90.0], "s1": [300.0, 300.0]}

trackAt = []
for s in (0.0, 0.3, 0.42, 1.0, 1.77, 2.05, 3.9, 4.5, 9.0):
    for interp in (True, False):
        trackAt.append({"s": s, "interp": interp, "v": FO.track_at(track_a, s, interp)})
smooth = []
for lmbd in (0.0, 1.5, 47.0, 900.0):
    y = [math.sin(i * 0.4) * 10 + (i % 3) for i in range(25)]
    w = [1.0 if i not in (8, 9, 10) else FO.HELD_WEIGHT for i in range(25)]
    smooth.append({"y": y, "w": w, "lmb": lmbd, "z": FO.smooth(y, w, lmbd)})
lams = [{"a": a, "fps": f, "v": FO.lam(a, f)} for a in (0, 0.3, 0.6, 1) for f in (24, 30)]
res = FO.resolve(project, metas, 30.0, lambda c: tuple(sizes[c["id"]]), lambda c, m: c["id"] != "m2")
autoAt = []
for cid, v in res.items():
    if "autoMotion" in v:
        for tau in (0.0, 0.0123, 0.5, 1.01, 7.0):
            autoAt.append({"clip": cid, "tau": tau, "v": M.auto_at(v["autoMotion"], tau)})
out = {"note": "generated by scripts/make_follow_cases.py from backend/app/follow.py",
       "trackA": track_a, "trackAt": trackAt, "smooth": smooth, "lam": lams, "unwrap": {"a": [170, -175, -160, 150, -40, 100], "v": FO.unwrap([170, -175, -160, 150, -40, 100])},
       "project": project, "metas": metas, "sizes": sizes, "resolved": res, "autoAt": autoAt}
(ROOT / "shared" / "follow_cases.json").write_text(json.dumps(r(out)), encoding="utf-8")
print("wrote shared/follow_cases.json:", {k: (len(v) if isinstance(v, (list, dict)) else v) for k, v in out.items() if k != "note"})
